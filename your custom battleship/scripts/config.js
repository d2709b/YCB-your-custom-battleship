// Up to 8.3 the mod id was "fling-bases" (Steam publishes the id as the title, so it was renamed). Saves, schematics and
// the machine data keep the old block names; they are read as the new ones.
var OLD_MOD = "fling-bases";
var LEGACY_BLOCKS = {"machine-builder-wheel": MOD + "-rocket-booster"};
function legacyBlockName(n){
    if(LEGACY_BLOCKS.hasOwnProperty(n)) return LEGACY_BLOCKS[n];
    if(typeof n == "string" && n.indexOf(OLD_MOD + "-") == 0) return MOD + n.substring(OLD_MOD.length);
    return n;
}

function boosterPower(){
    return Core.settings == null ? BASE_BOOSTER_POWER : Core.settings.getInt("mb-booster-power", BASE_BOOSTER_POWER);
}
function autoTurn(){
    return Core.settings == null ? true : Core.settings.getBool("mb-autoturn", true);
}

